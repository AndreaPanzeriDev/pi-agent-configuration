function parseDateToken(token: string): string | null {
	const t = token.toLowerCase();
	const today = localDateKey(new Date());
	if (t === "today") return today;
	if (t === "yesterday") return addDays(today, -1);
	if (/^\d{4}-\d{2}-\d{2}$/.test(t) && !Number.isNaN(new Date(`${t}T12:00:00`).getTime())) return t;
	return null;
}

const USAGE = "/report [today|yesterday|YYYY-MM-DD] [fast] · /report export [date] [file] · /daily is an alias";

async function handleReport(pi: ExtensionAPI, args: string, ctx: ExtensionCommandContext): Promise<void> {
	const tokens = (args ?? "").trim().split(/\s+/).filter(Boolean);
	const notify = (message: string, type: "info" | "warning" | "error" = "info") => {
		if (ctx.hasUI) ctx.ui.notify(message, type);
	};

	if (tokens.some((t) => t === "help" || t === "-h" || t === "--help")) {
		notify(USAGE, "info");
		return;
	}

	// --- export ---
	if (tokens[0]?.toLowerCase() === "export") {
		let date = localDateKey(new Date());
		let file = "";
		for (const t of tokens.slice(1)) {
			const d = parseDateToken(t);
			if (d) date = d;
			else if (!file) file = t;
		}
		const report = collectDay(date);
		const target = file ? path.resolve(ctx.cwd, file) : path.join(ctx.cwd, `report-${date}.md`);
		try {
			fs.writeFileSync(target, renderMarkdown(report), "utf8");
			notify(`Report saved to ${target} (${report.sessions.length} sessions)`, "info");
		} catch (error) {
			notify(`Export failed: ${String(error)}`, "error");
		}
		return;
	}

	// --- report ---
	let date = localDateKey(new Date());
	for (const t of tokens) {
		const d = parseDateToken(t);
		if (d) {
			date = d;
			break;
		}
	}
	const fast = tokens.some((t) => ["fast", "quick", "table", "table-only"].includes(t.toLowerCase()));

	const report = collectDay(date);
	if (report.sessions.length === 0) {
		notify(`No sessions with activity on ${date}.`, "warning");
		return;
	}

	// 1. Fast table (immediately).
	if (ctx.mode === "tui") {
		pi.appendEntry("daily-report-table", report);
	} else {
		// Outside the TUI (e.g. pi -p) there is no session or panel: print to stdout.
		process.stdout.write(renderMarkdown(report) + "\n");
		try {
			await pi.sendMessage(
				{ customType: "daily-report-table", content: renderMarkdown(report), display: true },
				{ triggerTurn: false },
			);
		} catch {
			/* no active session in this mode */
		}
	}

	// 2. AI summary (a single call, no tools).
	if (fast) {
		notify(`Table for ${date}: ${report.sessions.length} sessions, ${report.totalPrompts} prompts.`, "info");
		return;
	}
	if (!ctx.model) {
		notify("No model selected: showing the table only.", "warning");
		return;
	}
	notify("Generating the day summary…", "info");
	const summary = await generateSummary(ctx, buildDigest(report), englishDate(report.date));
	if (!summary) {
		notify("Summary failed (timeout or API error): keeping the table.", "warning");
		return;
	}
	if (ctx.mode !== "tui") {
		process.stdout.write(summary + "\n");
	}
	try {
		await pi.sendMessage(
			{ customType: "daily-report-summary", content: summary, display: true },
			{ triggerTurn: false },
		);
	} catch {
		/* no active session in this mode */
	}
}

// ---------------------------------------------------------------------------
// Extension
// ---------------------------------------------------------------------------

export default function (pi: ExtensionAPI) {
	pi.registerEntryRenderer("daily-report-table", (entry, _options, theme) => {
		try {
			const data = entry.data as DayReport | undefined;
			if (!data || !Array.isArray(data.sessions)) return undefined;
			return renderTablePanel(data, theme);
		} catch {
			return undefined;
		}
	});

	const completions = (prefix: string) => {
		const options = ["today", "yesterday", "fast", "export", "help"];
		const matches = options.filter((o) => o.startsWith(prefix.toLowerCase()));
		return matches.length > 0 ? matches.map((value) => ({ value, label: value })) : null;
	};

	for (const name of ["report", "daily"]) {
		pi.registerCommand(name, {
			description: "Day report: session table + done/not-finished summary",
			getArgumentCompletions: completions,
			handler: async (args, ctx) => {
				await handleReport(pi, args, ctx);
			},
		});
	}
}
